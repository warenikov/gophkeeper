// Команда client — CLI-приложение GophKeeper.
//
// Оно позволяет пользователю зарегистрироваться/аутентифицироваться на
// удалённом сервере GophKeeper и управлять своими приватными данными (пары
// логин/пароль, текст, банковские карты, бинарные данные и TOTP) локально и в
// синхронизации с сервером. Все чувствительные данные шифруются на клиенте,
// прежде чем покинуть машину (модель zero-knowledge).
package main

import (
	"fmt"
	"os"
)

func main() {
	if err := Execute(); err != nil {
		// SilenceErrors у корневой команды включён, поэтому печатаем ошибку
		// здесь — иначе сбой команды остался бы незамеченным.
		fmt.Fprintln(os.Stderr, "Ошибка:", err)
		os.Exit(1)
	}
}
