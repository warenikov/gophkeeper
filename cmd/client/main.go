// Команда client — CLI-приложение GophKeeper.
//
// Оно позволяет пользователю зарегистрироваться/аутентифицироваться на
// удалённом сервере GophKeeper и управлять своими приватными данными (пары
// логин/пароль, произвольный текст, бинарные данные и банковские карты)
// локально и в синхронизации с сервером. Все чувствительные данные шифруются
// на клиенте, прежде чем покинуть машину.
//
// Пока файл содержит точку входа и команду `version`; полное дерево команд
// добавляется в Спринте 1.
package main

import (
	"fmt"
	"os"

	"github.com/warenik/gophkeeper/internal/buildmeta"
)

func main() {
	// Минимальный бутстрап для Спринта 0: выводим информацию о сборке, чтобы
	// проверить работу тулчейна и проброс ldflags. Дерево команд на базе cobra
	// появится в Спринте 1.
	if len(os.Args) > 1 && (os.Args[1] == "version" || os.Args[1] == "--version") {
		fmt.Printf("gophkeeper-client %s\n", buildmeta.String())
		return
	}

	fmt.Printf("GophKeeper client (%s)\n", buildmeta.String())
	fmt.Println("Команды появятся в Спринте 1. Пока доступно: version")
}
